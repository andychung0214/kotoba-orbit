import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {createServer} from '../scripts/serve.js';
import {buildBank} from '../src/question-bank.js';
const server=createServer();await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const url=process.env.TEST_URL||`http://127.0.0.1:${server.address().port}`;
const browser=await chromium.launch({channel:'msedge',headless:true});
let count=0;const check=(name,ok)=>{assert.ok(ok,name);console.log('PASS '+name);count++;};
try{
 const page=await browser.newPage({viewport:{width:390,height:844}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{
  window.speechCalls=[];window.speechVoices=[{lang:'ja-JP',name:'Test Japanese',localService:true}];
  Object.defineProperty(window,'speechSynthesis',{value:{getVoices:()=>window.speechVoices,cancel:()=>window.speechCalls.push('cancel'),speak:u=>{window.lastUtterance=u;window.speechCalls.push({text:u.text,lang:u.lang,rate:u.rate});}}});
  Object.defineProperty(window,'SpeechSynthesisUtterance',{value:class {constructor(text){this.text=text;}}});
 });
 await page.goto(url+'#kana');await page.locator('.speak-button').first().waitFor();
 check('46 pairs have individual kana pronunciation buttons',await page.locator('.kana-cell .speak-button').count()===92);
 const first=page.locator('.speak-button').first();await first.click();
 check('click sends Japanese text and language',await page.evaluate(()=>window.lastUtterance.text==='あ'&&window.lastUtterance.lang==='ja-JP'));
 check('playing button exposes pressed state',await first.getAttribute('aria-pressed')==='true');
 await first.click();check('second click stops',await first.getAttribute('aria-pressed')==='false');
 await first.focus();await page.keyboard.press('Enter');check('keyboard starts pronunciation',await first.getAttribute('aria-pressed')==='true');
 await page.locator('#level').selectOption('advanced');await page.locator('.kana-cell').first().waitFor();
 check('difficulty replacement stops playback',await page.locator('[aria-pressed=true]').count()===0);
 check('advanced kana pronunciation is regenerated',await page.locator('.kana-cell .speak-button').count()===66);
 await page.evaluate(()=>location.hash='games');await page.locator('#level').selectOption('beginner');
 await page.locator('[data-start=match]').click();await page.locator('#dialog-body .speak-button').first().click();
 check('pronunciation does not select a matching answer',await page.locator('.match-button.selected').count()===0);
 check('no nested buttons',await page.locator('button button').count()===0);
 await page.locator('#close-dialog').click();await page.locator('#game-dialog').waitFor({state:'hidden'});
 check('closing dialog stops playback',await page.locator('[aria-pressed=true]').count()===0);
 await page.locator('[data-practice-type=order]').selectOption('cloze');await page.locator('[data-start=order]').click();
 const id=await page.locator('#dialog-body').getAttribute('data-question-id');const q=buildBank({mode:'order',level:'beginner',type:'cloze'}).find(q=>q.id===id);
 await page.locator('.question-main + .speak-button').click();
 check('cloze reads only the visible stem',await page.evaluate(()=>window.lastUtterance.text)===q.speechPrompt);
 check('pronunciation leaves answer untouched',await page.locator('#next-question').isHidden());
 await page.locator('[data-choice]').filter({hasText:q.answer}).click();
 await page.locator('.spoken-answer .speak-button').click();
 check('after answering full sentence can be spoken',await page.evaluate(()=>window.lastUtterance.text)===q.speechAnswer);
 await page.locator('#next-question').click();check('next question stops playback',await page.locator('[aria-pressed=true]').count()===0);
 await page.locator('.question-main + .speak-button').click();await page.evaluate(()=>window.lastUtterance.onerror({error:'network'}));
 check('engine error reports failure',await page.locator('#toast').textContent().then(t=>t.includes('播放失敗')));
 await page.evaluate(()=>window.speechVoices=[]);await page.locator('.question-main + .speak-button').click();
 check('missing Japanese voice reports setup guidance',await page.locator('#toast').textContent().then(t=>t.includes('日語語音')));
 check('modal speech notice is inside dialog and exposed to accessibility',await page.locator('#game-dialog #toast').count()===1&&(await page.locator('#game-dialog').ariaSnapshot()).includes('尚未找到日語語音'));
 check('mobile controls fit dialog',await page.locator('#game-dialog').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
 check('44px pronunciation targets',await page.locator('#dialog-body .speak-button').evaluateAll(es=>es.every(e=>e.getBoundingClientRect().height>=44)));
 await page.screenshot({path:'test-results/speech-mobile.png',fullPage:true});
 check('no uncaught browser errors',errors.length===0);
 const native=await browser.newPage();await native.goto(url+'#kana');
 console.log('Native speech availability (not an audible verification): '+JSON.stringify(await native.evaluate(()=>({supported:'speechSynthesis' in window,japaneseVoices:window.speechSynthesis?.getVoices().filter(v=>/^ja/i.test(v.lang)).length}))));
 await native.evaluate(()=>{
  window.nativeEvents=[];const original=window.speechSynthesis.speak.bind(window.speechSynthesis);
  window.speechSynthesis.speak=u=>{u.addEventListener('start',()=>window.nativeEvents.push('start'));u.addEventListener('end',()=>window.nativeEvents.push('end'));u.addEventListener('error',e=>window.nativeEvents.push('error:'+e.error));original(u);};
 });
 await native.locator('.speak-button').first().click();
 await native.waitForFunction(()=>window.nativeEvents.some(e=>e==='end'||e.startsWith('error:')),{},{timeout:15000}).catch(()=>{});
 console.log('Native engine events (not an audible verification): '+JSON.stringify(await native.evaluate(()=>window.nativeEvents)));
 console.log(`PASS ${count} pronunciation browser checks (mock speech engine)`);
}finally{await browser.close();await new Promise(resolve=>server.close(resolve));}
